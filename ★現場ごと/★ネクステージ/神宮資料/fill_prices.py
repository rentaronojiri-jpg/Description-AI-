def set_price(ws, row_num, price):
    """F列(col6)に単価を入力。G列(col7)が空ならD×Fを計算して入力。"""
    qty_cell = ws.cell(row=row_num, column=4)
    f_cell   = ws.cell(row=row_num, column=6)
    g_cell   = ws.cell(row=row_num, column=7)

    # G列に「別途」「弊社工事外」「無し」「不要」などのテキストがある行はスキップ
    if isinstance(g_cell.value, str) and not g_cell.value.startswith('='):
        return 0

    qty = qty_cell.value
    if qty is None or not isinstance(qty, (int, float)):
        qty = 1

    f_cell.value = price

    if g_cell.value is None:
        g_cell.value = int(round(qty * price))

    return int(round(qty * price))


